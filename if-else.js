// If

let age = 26;

if (age >= 18) {
  console.log("Adult");
}

// If Else

let number = 10;

if (number > 0) {
  console.log("Positive number");
} else {
  console.log("Negative number");
}

// Else If

let marks = 75;

if (marks >= 90) {
  console.log("Grade A");
} else if (marks >= 60) {
  console.log("Grade B");
} else if (marks >= 40) {
  console.log("Grade C");
} else {
  console.log("Fail");
}
